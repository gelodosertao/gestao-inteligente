async (page) => {
  page.setDefaultTimeout(8000);
  await page.goto('http://127.0.0.1:4173/gestao/configuracoes');
  await page.getByRole('button',{name:'Integração fiscal',exact:true}).click();
  const checks = [];
  const assert = (value, message) => { if (!value) throw new Error(message); };
  assert(await page.getByText('Integração fiscal não configurada',{exact:true}).isVisible(),'Settings notice missing');
  assert(await page.locator('input[type="file"], input[type="password"]').count() === 0, 'Fiscal secrets form remains');
  assert(await page.getByRole('button',{name:'Salvar Alterações',exact:true}).isDisabled(), 'Fiscal save enabled');
  checks.push('settings: no fiscal secrets form; save blocked');
  await page.screenshot({path:'output/playwright/fiscal-settings.png',fullPage:true});
  await page.goto('http://127.0.0.1:4173/gestao/relatorios');
  await page.getByRole('heading',{name:'Relatórios Detalhados'}).waitFor();
  await page.locator('body').ariaSnapshot();
  const csv = page.waitForEvent('download');
  await page.getByTitle('Exportar CSV').click();
  await (await csv).saveAs('output/playwright/management-report.csv');
  checks.push('management CSV export');
  await page.getByRole('button',{name:'Painel Fiscal'}).click();
  await page.locator('body').ariaSnapshot();
  assert(await page.getByText('Integração fiscal não configurada',{exact:true}).isVisible(),'Reports notice missing');
  assert(await page.getByRole('button',{name:'Baixar Lote de XMLs'}).isDisabled(),'Fiscal XML export enabled');
  assert(await page.getByRole('button',{name:'Resumo Contábil'}).isDisabled(),'Fiscal report enabled');
  checks.push('fiscal exports blocked');
  await page.screenshot({path:'output/playwright/fiscal-reports.png',fullPage:true});
  await page.goto('http://127.0.0.1:4173/gestao/estoque');
  await page.getByText('GELO TESTE LOCAL',{exact:true}).first().waitFor();
  checks.push('inventory loaded');
  await page.goto('http://127.0.0.1:4173/gestao/clientes');
  await page.getByRole('cell',{name:'CLIENTE TESTE LOCALMatriz',exact:true}).waitFor();
  checks.push('customers loaded');
  await page.goto('http://127.0.0.1:4173/pdv-atacado');
  await page.getByRole('button',{name:'Vendas',exact:true}).waitFor();
  await page.locator('body').ariaSnapshot();
  await page.getByRole('button',{name:'Vendas',exact:true}).click();
  await page.locator('body').ariaSnapshot();
  assert(await page.getByRole('button',{name:'DANFE',exact:true}).isDisabled(),'DANFE enabled');
  await page.getByRole('button',{name:'Nota fiscal',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  assert(await page.getByText('Integração fiscal não configurada',{exact:true}).isVisible(),'Modal notice missing');
  assert(await page.getByRole('dialog').getByText('TEST-PROTOCOL-123',{exact:true}).isVisible(),'Stored history unavailable in POS');
  await page.keyboard.press('Escape');
  assert(await page.getByRole('dialog').count() === 0,'Modal did not close');
  checks.push('wholesale: DANFE blocked, stored history, modal closes');
  await page.goto('http://127.0.0.1:4173/pdv-adega');
  await page.getByText('GELO TESTE LOCAL',{exact:true}).waitFor();
  const state = await page.evaluate(() => window.fiscalTestState());
  assert(state.fiscalRequests.length === 0, 'Unexpected fiscal request');
  assert(state.errors.length === 0, 'Browser errors: '+state.errors.join(';'));
  return {checks, fiscalRequests:state.fiscalRequests, errors:state.errors};
}